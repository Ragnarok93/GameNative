package com.winlator.core

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class DXVKHelperTest {
    @Test
    fun autoGeneratedVramConfigUsesActualDxvkEnvironmentGrammar() {
        val config = DXVKHelper.buildDxvkConfig(KeyValueSet("maxDeviceMemory=3072"))
        assertEquals(
            "dxgi.maxDeviceMemory = 3072; dxgi.maxSharedMemory = 3072",
            config,
        )
        assertFalse(config.startsWith("\""))
        assertFalse(config.endsWith("\""))
        assertFalse(config.contains("\n"))
    }

    @Test
    fun disabledVramDoesNotInventHardQuota() {
        assertEquals("", DXVKHelper.buildDxvkConfig(KeyValueSet("maxDeviceMemory=0")))
        assertEquals("", DXVKHelper.buildDxvkConfig(KeyValueSet()))
    }

    @Test
    fun featureLevelAndCustomGpuRemainSeparateOptions() {
        val config = DXVKHelper.buildDxvkConfig(
            KeyValueSet(
                "maxDeviceMemory=3072,maxFeatureLevel=11_0,customDevice=1B80:10DE:NVIDIA GeForce GTX 480,constantBufferRangeCheck=true"
            )
        )
        assertTrue(config.contains("; d3d11.maxFeatureLevel = 11_0"))
        assertTrue(config.contains("; dxgi.customDeviceId = 1B80"))
        assertTrue(config.contains("; dxgi.customDeviceDesc = \"NVIDIA GeForce GTX 480\""))
        assertTrue(config.contains("; d3d11.constantBufferRangeCheck = \"True\""))
        assertFalse(config.startsWith("\""))
    }

    @Test
    fun noLeadingShellQuotesInAnyConfig() {
        val configs = listOf(
            "maxDeviceMemory=2048",
            "maxFeatureLevel=11_0",
            "customDevice=1234:5678:Test GPU",
            "constantBufferRangeCheck=true",
        )
        configs.forEach { raw ->
            val value = DXVKHelper.buildDxvkConfig(KeyValueSet(raw))
            assertFalse("Outer shell quotes cannot be parsed by DXVK: $raw", value.startsWith("\""))
            // A quoted GPU description is a legitimate DXVK value. Only a
            // shell quote that wraps the *entire* environment is forbidden.
            if (!raw.startsWith("customDevice=")) {
                assertFalse("No trailing outer quote: $raw", value.endsWith("\""))
            }
        }
    }
}
